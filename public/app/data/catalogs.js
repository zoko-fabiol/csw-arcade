/**
 * Catalogues unifiés CSW-Arcade (4 Modes : Arcade, PlayStation, Xbox, Nintendo).
 * Privilégie un maximum de jeux légers (< 150 Mo) avec ROMs vérifiées sur Archive.org
 * pour le téléchargement automatique et le lancement en 1 clic.
 */

function iaUrls(identifier, filePath) {
  const encodedPath = filePath
    .split('/')
    .map((s) => encodeURIComponent(s))
    .join('/');
  const dl = `https://archive.org/download/${encodeURIComponent(identifier)}/${encodedPath}`;
  return [
    `https://archive.org/cors/${encodeURIComponent(identifier)}/${encodedPath}`,
    `/api/rom-proxy?url=${encodeURIComponent(dl)}`,
    dl,
  ];
}

